"""Procedural cover art rendered with Pillow.

This provider needs no model weights, no network and no GPU, so the app can
always produce a finished cover.  It is used as the fallback when a
diffusion model is not installed, and it also renders the title and author
typography for covers generated by other providers.
"""

from __future__ import annotations

import random
from pathlib import Path

from PIL import Image, ImageDraw, ImageFilter

from .base import CoverProvider, CoverRequest, CoverResult
from .theme import build_prompt, detect_genre, palette_for
from .typography import draw_centered_text, fit_font, load_font, text_size, wrap_text


class PillowCoverProvider(CoverProvider):
    """Draws an elegant typographic cover from scratch."""

    name = "pillow"
    label = "Built-in designer (offline, instant)"
    requirements = "Always available"

    def is_available(self) -> bool:
        return True

    # ------------------------------------------------------------------ #
    def generate(self, request: CoverRequest, progress=None) -> CoverResult:
        if progress:
            progress("Designing cover...")

        genre, hits = detect_genre(request.story_text)
        palette = palette_for(genre)
        width = max(256, request.width)
        height = max(256, request.height)
        seed = request.seed if request.seed and request.seed >= 0 else abs(hash(request.title)) % 100000

        image = self._background(width, height, palette, seed)
        image = self._ornament(image, palette, seed)
        image = self._typography(image, request, palette)

        output_path = Path(request.output_path)
        output_path.parent.mkdir(parents=True, exist_ok=True)
        image.save(output_path, "PNG", dpi=(300, 300))

        return CoverResult(
            path=output_path,
            provider=self.name,
            prompt=build_prompt(genre, request.title, request.author, request.extra_prompt),
            genre=genre,
        )

    # ------------------------------------------------------------------ #
    def _background(self, width: int, height: int, palette, seed: int) -> Image.Image:
        """Vertical gradient with a soft glow behind the title."""
        top = palette[0]
        bottom = palette[1]
        accent = palette[2]

        image = Image.new("RGB", (width, height), top)
        draw = ImageDraw.Draw(image)

        for y in range(height):
            ratio = y / max(1, height - 1)
            eased = ratio * ratio * (3 - 2 * ratio)  # smoothstep
            colour = tuple(
                int(top[i] + (bottom[i] - top[i]) * eased) for i in range(3)
            )
            draw.line([(0, y), (width, y)], fill=colour)

        # Soft radial glow.
        glow = Image.new("RGB", (width, height), (0, 0, 0))
        glow_draw = ImageDraw.Draw(glow)
        cx, cy = width // 2, int(height * 0.38)
        radius = int(min(width, height) * 0.55)
        steps = 28
        for step in range(steps, 0, -1):
            r = int(radius * step / steps)
            intensity = (1 - step / steps) ** 2
            colour = tuple(int(c * intensity) for c in accent)
            glow_draw.ellipse([cx - r, cy - r, cx + r, cy + r], fill=colour)
        glow = glow.filter(ImageFilter.GaussianBlur(radius=60))

        return Image.blend(image, Image.blend(image, glow, 0.45), 0.55)

    def _ornament(self, image: Image.Image, palette, seed: int) -> Image.Image:
        """Add abstract shapes that hint at the story's mood."""
        width, height = image.size
        rng = random.Random(seed)
        layer = Image.new("RGBA", (width, height), (0, 0, 0, 0))
        draw = ImageDraw.Draw(layer)

        accent = palette[2]
        style = rng.choice(["arcs", "rings", "mountains"])

        if style == "arcs":
            for index in range(5):
                offset = int(height * (0.16 + index * 0.07))
                span = int(width * (0.55 + index * 0.12))
                alpha = 30 - index * 4
                draw.arc(
                    [width // 2 - span, offset - span // 3, width // 2 + span, offset + span // 3],
                    start=200,
                    end=340,
                    fill=(*accent, max(8, alpha)),
                    width=max(2, 8 - index),
                )
        elif style == "rings":
            for index in range(7):
                r = int(min(width, height) * (0.12 + index * 0.07))
                cx = rng.randint(int(width * 0.15), int(width * 0.85))
                cy = rng.randint(int(height * 0.2), int(height * 0.85))
                draw.ellipse([cx - r, cy - r, cx + r, cy + r], outline=(*accent, 34), width=2)
        else:  # mountains
            points = [(0, height)]
            peaks = rng.randint(3, 5)
            for index in range(peaks + 1):
                x = int(width * index / peaks)
                y = int(height * rng.uniform(0.62, 0.85))
                points.append((x, y))
            points.append((width, height))
            draw.polygon(points, fill=(*accent, 26))

        layer = layer.filter(ImageFilter.GaussianBlur(1.2))
        image = image.convert("RGBA")
        image.alpha_composite(layer)

        # Vignette.
        vignette = Image.new("L", (width, height), 0)
        v_draw = ImageDraw.Draw(vignette)
        v_draw.ellipse(
            [-int(width * 0.25), -int(height * 0.2), int(width * 1.25), int(height * 1.2)],
            fill=255,
        )
        vignette = vignette.filter(ImageFilter.GaussianBlur(radius=int(min(width, height) * 0.18)))
        dark = Image.new("RGBA", (width, height), (0, 0, 0, 255))
        image = Image.composite(image, dark, vignette)
        return image.convert("RGB")

    def _typography(self, image: Image.Image, request: CoverRequest, palette) -> Image.Image:
        """Draw the title, rule and author onto the artwork."""
        width, height = image.size
        draw = ImageDraw.Draw(image)
        margin = int(width * 0.10)
        inner_width = width - margin * 2

        title = (request.title or "Untitled Story").strip()
        author = (request.author or "").strip()

        # Title block, vertically centred a little above the middle.
        max_title_height = int(height * 0.28)
        title_font, title_lines = fit_font(
            draw,
            title,
            max_width=inner_width,
            max_height=max_title_height,
            max_size=int(height * 0.115),
            min_size=24,
            bold=True,
        )
        _, line_height = text_size(draw, "Ag", title_font)
        title_block_height = int(line_height * 1.18 * len(title_lines))
        title_y = int(height * 0.34) - title_block_height // 2

        shadow = (10, 8, 16)
        draw_centered_text(
            draw, "\n".join(title_lines), title_font, width // 2, title_y + 4,
            fill=shadow, stroke_width=0,
        )
        draw_centered_text(
            draw, "\n".join(title_lines), title_font, width // 2, title_y,
            fill=(255, 255, 255), stroke_width=max(2, int(width * 0.004)),
            stroke_fill=shadow,
        )

        # Decorative rule under the title.
        rule_y = title_y + title_block_height + int(height * 0.045)
        rule_width = int(inner_width * 0.28)
        rule_colour = tuple(min(255, c + 60) for c in palette[2])
        draw.line(
            [(width // 2 - rule_width // 2, rule_y), (width // 2 + rule_width // 2, rule_y)],
            fill=rule_colour,
            width=max(2, int(height * 0.004)),
        )

        # Author.
        if author:
            author_font = load_font(int(height * 0.032), bold=False)
            author_lines = wrap_text(draw, author.upper(), author_font, inner_width)
            author_y = int(height * 0.78)
            for line in author_lines:
                draw_centered_text(
                    draw, line, author_font, width // 2, author_y,
                    fill=(244, 240, 232), stroke_width=max(1, int(width * 0.002)),
                    stroke_fill=shadow,
                )
                author_y += int(line_height * 0.9)

        return image


def apply_title_overlay(image: Image.Image, title: str, author: str) -> Image.Image:
    """Overlay a title and author onto an existing image.

    Used by the diffusion providers, which do not render text themselves.
    """
    width, height = image.size
    draw = ImageDraw.Draw(image)
    margin = int(width * 0.09)
    inner_width = width - margin * 2

    title_font, title_lines = fit_font(
        draw,
        (title or "").strip(),
        max_width=inner_width,
        max_height=int(height * 0.24),
        max_size=int(height * 0.095),
        min_size=22,
        bold=True,
    )
    _, line_height = text_size(draw, "Ag", title_font)
    title_y = int(height * 0.07)

    draw_centered_text(
        draw, "\n".join(title_lines), title_font, width // 2, title_y + 3,
        fill=(8, 6, 12), stroke_width=0,
    )
    draw_centered_text(
        draw, "\n".join(title_lines), title_font, width // 2, title_y,
        fill=(255, 255, 255), stroke_width=max(2, int(width * 0.004)),
        stroke_fill=(8, 6, 12),
    )

    if author:
        author_font = load_font(int(height * 0.030), bold=False)
        author_y = int(height * 0.90)
        for line in wrap_text(draw, author.upper(), author_font, inner_width):
            draw_centered_text(
                draw, line, author_font, width // 2, author_y,
                fill=(240, 236, 228), stroke_width=max(1, int(width * 0.002)),
                stroke_fill=(8, 6, 12),
            )
            author_y += int(line_height * 0.85)

    return image

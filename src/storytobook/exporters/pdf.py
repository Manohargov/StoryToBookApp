"""PDF renderer built on fpdf2.

When a TrueType font is available the book is typeset with full unicode
support.  Otherwise the renderer falls back to the built-in Helvetica core
font and transliterates the text so the PDF is still produced.
"""

from __future__ import annotations

import importlib.util
import unicodedata
from pathlib import Path

from ..errors import ExportError
from ..providers.cover.typography import find_font
from .base import BookDocument, BookExporter

_INSTALL_HINT = "Install it with:  pip install fpdf2"

#: Core fonts only understand latin-1, so these characters are replaced.
_REPLACEMENTS = {
    "\u2018": "'", "\u2019": "'", "\u201c": '"', "\u201d": '"',
    "\u2013": "-", "\u2014": "-", "\u2026": "...", "\u00a0": " ",
}


def to_latin1(text: str) -> str:
    """Reduce text to characters the built-in PDF fonts understand."""
    out = []
    for char in text or "":
        replacement = _REPLACEMENTS.get(char)
        if replacement is not None:
            out.append(replacement)
            continue
        try:
            char.encode("latin-1")
        except UnicodeEncodeError:
            decomposed = unicodedata.normalize("NFKD", char)
            stripped = "".join(c for c in decomposed if not unicodedata.combining(c))
            try:
                stripped.encode("latin-1")
            except UnicodeEncodeError:
                stripped = ""
            out.append(stripped)
        else:
            out.append(char)
    return "".join(out)


class PdfExporter(BookExporter):
    """Typesets a book as a print-ready PDF."""

    name = "pdf"
    label = "PDF (print ready)"
    extension = ".pdf"

    def is_available(self) -> bool:
        return importlib.util.find_spec("fpdf") is not None

    # ------------------------------------------------------------------ #
    def export(self, document: BookDocument, output_dir: Path, filename_stem: str) -> Path:
        if not self.is_available():
            raise ExportError(
                "The 'fpdf2' package is required to build PDFs.", _INSTALL_HINT
            )

        output_dir = Path(output_dir)
        output_dir.mkdir(parents=True, exist_ok=True)
        output_path = output_dir / f"{filename_stem}{self.extension}"

        # A5 is 148 x 210 mm.  The size is given explicitly so the layout
        # does not shift between fpdf2 releases.
        pdf = _book_pdf_class()(orientation="P", unit="mm", format=(148, 210))
        pdf.set_auto_page_break(auto=True, margin=18)
        pdf.set_margins(18, 18, 18)
        pdf.alias_nb_pages()

        unicode_font = self._register_font(pdf)
        family = "Book" if unicode_font else "Helvetica"

        def set_font(style: str = "", size: int = 11) -> None:
            try:
                pdf.set_font(family, style=style, size=size)
            except Exception:
                # The requested variant was not registered - use the regular one.
                pdf.set_font(family, size=size)

        def body(text: str) -> str:
            return text if unicode_font else to_latin1(text)

        self._cover(pdf, document, set_font, body)
        self._title_page(pdf, document, set_font, body)
        self._front_matter(pdf, document, set_font, body)
        self._contents(pdf, document, set_font, body)
        self._chapters(pdf, document, set_font, body)
        self._colophon(pdf, document, set_font, body)

        try:
            pdf.output(str(output_path))
        except Exception as exc:
            raise ExportError(f"Could not write the PDF: {exc}") from exc

        return output_path

    # ------------------------------------------------------------------ #
    def _register_font(self, pdf) -> bool:
        """Register a TrueType family; return True when unicode is supported."""
        regular = find_font()
        bold = find_font(bold=True)
        italic = find_font(italic=True)
        if not regular and not bold:
            return False
        try:
            pdf.add_font("Book", style="", fname=regular or bold)
            if bold:
                pdf.add_font("Book", style="B", fname=bold)
            if italic:
                pdf.add_font("Book", style="I", fname=italic)
            pdf.set_font("Book", size=11)
            return True
        except Exception:
            return False

    def _cover(self, pdf, document: BookDocument, set_font, body) -> None:
        pdf.add_page()
        cover = document.cover_path
        if cover and Path(cover).exists():
            try:
                pdf.image(str(cover), x=12, y=12, w=pdf.w - 24)
                pdf.set_y(-20)
                set_font("I", 8)
                pdf.cell(0, 6, "Cover artwork generated by StoryToBook", align="C")
                return
            except Exception:
                pass  # fall through to the typographic cover

        pdf.ln(45)
        set_font("B", 26)
        pdf.multi_cell(0, 12, body(document.title), align="C")
        pdf.ln(10)
        set_font("", 14)
        subtitle = f"by {document.author}" if document.author else ""
        pdf.multi_cell(0, 8, body(subtitle), align="C")

    def _title_page(self, pdf, document: BookDocument, set_font, body) -> None:
        pdf.add_page()
        pdf.ln(55)
        set_font("B", 24)
        pdf.multi_cell(0, 11, body(document.title), align="C")
        pdf.ln(12)
        set_font("", 14)
        if document.author:
            pdf.multi_cell(0, 8, body(document.author), align="C")
        if document.publisher:
            pdf.ln(45)
            set_font("I", 11)
            pdf.multi_cell(0, 7, body(document.publisher), align="C")

    def _front_matter(self, pdf, document: BookDocument, set_font, body) -> None:
        pdf.add_page()
        set_font("B", 16)
        pdf.multi_cell(0, 9, "Acknowledgment", align="L")
        pdf.ln(4)
        set_font("", 11)
        text = document.acknowledgment.strip() or "Thank you for reading."
        pdf.multi_cell(0, 6, body(text), align="J")

        pdf.ln(12)
        set_font("B", 16)
        pdf.multi_cell(0, 9, "Author's Note", align="L")
        pdf.ln(4)
        set_font("", 11)
        note = document.author_note.strip() or "Written with StoryToBook."
        pdf.multi_cell(0, 6, body(note), align="J")

    def _contents(self, pdf, document: BookDocument, set_font, body) -> None:
        pdf.add_page()
        set_font("B", 18)
        pdf.multi_cell(0, 10, "Contents", align="C")
        pdf.ln(8)
        set_font("", 11)
        for index, chapter in enumerate(document.chapters, start=1):
            title = chapter.title.strip() or f"Chapter {index}"
            pdf.multi_cell(0, 7, body(title), align="L")
            pdf.ln(1)

    def _chapters(self, pdf, document: BookDocument, set_font, body) -> None:
        for index, chapter in enumerate(document.chapters, start=1):
            pdf.add_page()
            title = chapter.title.strip() or f"Chapter {index}"
            set_font("B", 18)
            pdf.multi_cell(0, 10, body(title), align="C")
            pdf.ln(3)
            set_font("", 11)
            paragraphs = [p.strip() for p in (chapter.text or "").split("\n") if p.strip()]
            for paragraph in paragraphs or [""]:
                pdf.multi_cell(0, 6, body(paragraph), align="J")
                pdf.ln(3)

    def _colophon(self, pdf, document: BookDocument, set_font, body) -> None:
        pdf.add_page()
        pdf.ln(80)
        set_font("I", 12)
        pdf.multi_cell(0, 7, "Thank you for reading!", align="C")
        pdf.ln(14)
        set_font("", 11)
        if document.author:
            pdf.multi_cell(0, 7, body(f"Written by {document.author}"), align="C")
        if document.publisher:
            pdf.ln(4)
            pdf.multi_cell(0, 7, body(f"Published by {document.publisher}"), align="C")
        pdf.ln(14)
        set_font("I", 9)
        pdf.multi_cell(0, 6, body("All rights reserved."), align="C")


def _book_pdf_class():
    """Create the FPDF subclass that draws the running footer."""
    from fpdf import FPDF  # noqa: PLC0415 - optional dependency

    class _BookPDF(FPDF):
        """A5 book with a page-number footer."""

        def footer(self) -> None:
            self.set_y(-15)
            try:
                self.set_font("Book", style="I", size=8)
            except Exception:
                self.set_font("Helvetica", style="I", size=8)
            # fpdf2 replaces the {nb} alias with the final page count on close.
            self.cell(0, 8, f"- {self.page_no()} / {{nb}} -", align="C")

    return _BookPDF
